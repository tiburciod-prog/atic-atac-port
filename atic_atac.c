/*
 * draw_room_outline() — draw vector wall lines for this room style.
 */
static void draw_room_outline(SDL_Renderer *ren, int style, SDL_Color c) {
    switch (style) {
        case 0: draw_wall_lines(ren, c, walls_square,  6); break;
        case 1: draw_wall_lines(ren, c, walls_tall,    6); break;
        case 2: draw_wall_lines(ren, c, walls_wide,    6); break;
        case 3: draw_wall_lines(ren, c, walls_octagon, 24); break;
        default: draw_wall_lines(ren, c, walls_square, 6); break;
    }
}

/*
 * render_room() — fill floor and draw walls for the current room.
 * Must be called each frame before rendering sprites.
 */
static void render_room(SDL_Renderer *ren, const GameState *gs) {
    int style_idx = room_attrs[gs->current_room].style;

    /* Decode ZX attribute → SDL colours */
    uint8_t attr  = gs->room_attr;
    int bright    = (attr & 0x40) ? 8 : 0;
    SDL_Color ink  = zx_pal[(attr & 7) | bright];

    /* Step 1: Fill entire game area with wall (ink) colour */
    SDL_SetRenderDrawColor(ren, ink.r, ink.g, ink.b, 255);
    SDL_Rect game_area = { 0, 0, WIN_W, WIN_H };
    SDL_RenderFillRect(ren, &game_area);

    /* Step 2: Clear floor interior to black using room_sizes table.
     * floor_rects[style]: {sdl_x, sdl_y, sdl_w, sdl_h} derived from BBC room_sizes.
     * BBC coords → SDL: x * SCREEN_W*SCALE/120, y * SCALE */
    /* Floor cut-out rectangles from BBC wall data (2nd RECT entry = floor interior).
     * BBC: RECT (x,y,w,h) → SDL: x*256*SCALE/120, y*SCALE, w*256*SCALE/120, h*SCALE
     * SCALE=3, 256*3/120 = 6.4 */
    static const int floor_rects[11][4] = {
        {108, 93, 544, 387},  /* 0: plain square  BBC (17,31,85,129) */
        {249, 93, 262, 387},  /* 1: tall          BBC (39,31,41,129) */
        {108,177, 544, 219},  /* 2: wide          BBC (17,59,85, 73) */
        {108, 93, 544, 387},  /* 3: octagon       (all lines, use square fallback) */
        {108, 93, 544, 387},  /* 4: cavern square (fallback) */
        {249, 93, 262, 387},  /* 5: cavern tall   (fallback) */
        {108,177, 544, 219},  /* 6: cavern wide   (fallback) */
        {249, 93, 262, 387},  /* 7: stairs vert   (same as tall) */
        {108,177, 544, 219},  /* 8: stairs horiz  (same as wide) */
        {108, 93, 544, 387},  /* 9: wide cave     (same as square) */
        {249, 93, 262, 387},  /* 10: tall cave    (same as tall) */
    };
    int si = (style_idx >= 0 && style_idx <= 10) ? style_idx : 0;
    SDL_SetRenderDrawColor(ren, 0, 0, 0, 255);
    SDL_Rect floor_r = { floor_rects[si][0], floor_rects[si][1],
                         floor_rects[si][2], floor_rects[si][3] };
    SDL_RenderFillRect(ren, &floor_r);

    /* Step 3: Draw decorative vector lines over the wall band (inner detail lines) */
    draw_room_outline(ren, style_idx, ink);
}

int main(int argc, char *argv[]) {
    int headless = 0;
    int screenshot = 0;
    for (int i = 1; i < argc; i++) {
        if (strcmp(argv[i], "--headless") == 0) headless = 1;
        if (strcmp(argv[i], "--screenshot") == 0) { headless = 1; screenshot = 1; }
    }

    /* Allocate RAM */
    uint8_t *ram = calloc(RAM_SIZE, 1);
    if (!ram) { fprintf(stderr, "Out of memory\n"); return 1; }

    /* Game state */
    GameState gs;
    memset(&gs, 0, sizeof(gs));

    /* Load game data: full snapshot preferred, TAP fallback */
    if (!load_z80("atic_atac_full.z80", ram)) {
        if (!load_tap("ATIC_ATAC.TAP", ram)) {
            fprintf(stderr, "Using blank RAM (no valid snapshot)\n");
        }
    }

    /* Init game state from snapshot */
    init_game(&gs, ram);
    gs.ram = ram;
    parse_room_table(&gs, ram);
    parse_room_entities(&gs, ram);

    /* SDL init */
    if (SDL_Init(SDL_INIT_VIDEO) != 0) {
        fprintf(stderr, "SDL_Init: %s\n", SDL_GetError());
        free(ram);
        return 1;
    }

    Uint32 win_flags = headless ? SDL_WINDOW_HIDDEN : 0;
    SDL_Window *win = SDL_CreateWindow(
        "Atic Atac — ZX Spectrum Port",
        SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED,
        WIN_W, WIN_H, win_flags);
    if (!win) {
        fprintf(stderr, "SDL_CreateWindow: %s\n", SDL_GetError());
        SDL_Quit(); free(ram); return 1;
    }

    SDL_Renderer *ren = SDL_CreateRenderer(win, -1,
        SDL_RENDERER_ACCELERATED | SDL_RENDERER_PRESENTVSYNC);
    if (!ren) {
        SDL_DestroyWindow(win); SDL_Quit(); free(ram); return 1;
    }
    SDL_RenderSetLogicalSize(ren, WIN_W, WIN_H);

    /* Character select (skip in headless mode) */
    if (!headless) {
        gs.char_type = (uint8_t)show_char_select(ren);
    }

    SDL_Texture *tex = SDL_CreateTexture(ren,
        SDL_PIXELFORMAT_ARGB8888,
        SDL_TEXTUREACCESS_STREAMING,
        SCREEN_W, SCREEN_H);
    if (!tex) {
        SDL_DestroyRenderer(ren); SDL_DestroyWindow(win); SDL_Quit(); free(ram); return 1;
    }

    SDL_Rect dst = {0, 0, WIN_W, WIN_H};
    (void)dst;  /* kept for future sprite blit */

    /* Main loop */
    while (gs.running) {
        SDL_Event ev;
        while (SDL_PollEvent(&ev)) {
            if (ev.type == SDL_QUIT) gs.running = 0;
            if (ev.type == SDL_KEYDOWN && ev.key.keysym.sym == SDLK_ESCAPE) gs.running = 0;
            if (ev.type == SDL_KEYDOWN && ev.key.keysym.sym == SDLK_SPACE) fire_weapon(&gs);
        }

        /* Player movement — arrow keys / WASD, 2px per frame */
        {
            const Uint8 *keys = SDL_GetKeyboardState(NULL);
            int nx = gs.player.x;
            int ny = gs.player.y;
            int moved = 0;

            if (keys[SDL_SCANCODE_LEFT]  || keys[SDL_SCANCODE_A])
                { nx -= 2; gs.walk_dir = 2; moved = 1; }
            if (keys[SDL_SCANCODE_RIGHT] || keys[SDL_SCANCODE_D])
                { nx += 2; gs.walk_dir = 1; moved = 1; }
            if (keys[SDL_SCANCODE_UP]    || keys[SDL_SCANCODE_W])
                { ny -= 2; gs.walk_dir = 3; moved = 1; }
            if (keys[SDL_SCANCODE_DOWN]  || keys[SDL_SCANCODE_S])
                { ny += 2; gs.walk_dir = 0; moved = 1; }

            /* Door-based room transitions: check proximity to door entities */
            for (int di = 0; di < gs.num_room_entities; di++) {
                const RoomEntity *re = &gs.room_entities[di];
                /* Secret passages: character-specific entities */
                {
                    static const uint8_t pass_gfx[3] = {0x10, 0x17, 0x1A}; /* Knight=clock, Wizard=bookcase, Serf=barrel */
                    if (re->graphic == pass_gfx[gs.char_type & 0x03u] ||
                        (gs.char_type > 2 && re->graphic == 0x10)) {
                        int dpx = nx - (int)re->x;
                        int dpy = ny - (int)re->y;
                        if (dpx*dpx + dpy*dpy < 144) {
                            do_room_transition(&gs, re->zx_addr);
                            break;
                        }
                    }
                }
                int is_normal = (re->graphic >= 0x01 && re->graphic <= 0x03);
                int is_locked = (re->graphic >= 0x08 && re->graphic <= 0x0B);
                int is_trapdoor = (re->graphic == 0x19);
                if (!is_normal && !is_locked && !is_trapdoor) continue;
                int ddx = nx - (int)re->x;
                int ddy = ny - (int)re->y;
                if (ddx*ddx + ddy*ddy < 144) { /* 12px trigger radius */
                    if (is_locked && !has_key_for_door(&gs, re->attr)) {
                        /* No key — block player at door position */
                        nx = (int)re->x;
                        ny = (int)re->y;
                        break;
                    }
                    do_room_transition(&gs, re->zx_addr);
                    nx = gs.player.x;
                    ny = gs.player.y;
                    break;
                }
            }
            /* Clamp to room interior if no transition triggered */
            {
                const RoomStyle *rs2 = get_room_style(gs.current_room, NULL);
                int cx2 = 0x58, cy2 = 0x68;
                int lb = cx2 - rs2->w + 4;
                int rb = cx2 + rs2->w - 4 - 16;
                int tb = cy2 - rs2->h + 4;
                int bb = cy2 + rs2->h - 4 - 18;
                if (nx < lb) nx = lb;
                if (nx > rb) nx = rb;
                if (ny < tb) ny = tb;
                if (ny > bb) ny = bb;
            }

            gs.player.x = (uint8_t)nx;
            gs.player.y = (uint8_t)ny;

            /* Advance walk animation every 6 frames when moving */
            if (moved && (gs.frame % 6 == 0))
                gs.walk_frame = (gs.walk_frame + 1) & 3;
        }

        SDL_SetRenderDrawColor(ren, 0, 0, 0, 255);  /* ZX border: black */
        SDL_RenderClear(ren);
        render_room(ren, &gs);
        render_items(ren, &gs);
        render_decorations(ren, &gs);
        render_player(ren, &gs);
        render_creatures(ren, &gs);
        render_weapon(ren, &gs);
        render_hud(ren, &gs);
        SDL_RenderPresent(ren);

        if (headless) {
            fprintf(stdout, "Headless: frame rendered OK\n");
            if (screenshot) {
                SDL_Surface *sshot = SDL_CreateRGBSurface(0, WIN_W, WIN_H, 32,
                    0x00FF0000, 0x0000FF00, 0x000000FF, 0xFF000000);
                if (sshot) {
                    SDL_RenderReadPixels(ren, NULL, SDL_PIXELFORMAT_ARGB8888,
                        sshot->pixels, sshot->pitch);
                    SDL_SaveBMP(sshot, "/tmp/atic_screenshot.bmp");
                    SDL_FreeSurface(sshot);
                }
            }
            gs.running = 0;
        } else {
            SDL_Delay(1000 / FPS);
        }

        gs.frame++;
        game_tick(&gs);
    }

    /* Game over overlay: red tint for 2 seconds */
    if (!headless && gs.energy == 0 && gs.lives == 0) {
        SDL_SetRenderDrawBlendMode(ren, SDL_BLENDMODE_BLEND);
        SDL_SetRenderDrawColor(ren, 200, 0, 0, 128);
        SDL_Rect overlay = {0, 0, WIN_W, WIN_H};
        SDL_RenderFillRect(ren, &overlay);
        SDL_RenderPresent(ren);
        SDL_Delay(2000);
    }

    SDL_DestroyTexture(tex);
    SDL_DestroyRenderer(ren);
    SDL_DestroyWindow(win);
    SDL_Quit();
    free(ram);
    return 0;
}

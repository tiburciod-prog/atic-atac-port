/*
 * check_item_pickup() — collect ACG key piece if player is within 10px.
 * Sets running=0 after collecting all 3 and reaching exit (graphic 0x24).
 */
static void check_item_pickup(GameState *gs) {
    for (int i = 0; i < gs->num_room_entities; i++) {
        RoomEntity *e = &gs->room_entities[i];
        int dx = (int)gs->player.x - (int)e->x;
        int dy = (int)gs->player.y - (int)e->y;
        if (dx*dx + dy*dy >= 144) continue; /* 12px pickup radius */

        /* Food items: graphic $80-$89 — restore +64 energy */
        if (e->graphic >= 0x80 && e->graphic <= 0x89) {
            e->graphic = 0x00; /* consume */
            if (gs->energy < 0xF0 - 64)
                gs->energy = (uint8_t)(gs->energy + 64);
            else
                gs->energy = 0xF0;
            gs->score_val += 100;
            uint32_t s = gs->score_val;
            gs->score[2] = (uint8_t)(((s/10)%10)<<4|(s%10));
            gs->score[1] = (uint8_t)(((s/1000)%10)<<4|((s/100)%10));
            gs->score[0] = (uint8_t)(((s/100000)%10)<<4|((s/10000)%10));
            fprintf(stdout, "Food! energy=%d\n", gs->energy);
            continue;
        }

        /* ACG key pieces: graphic $8C-$8E */
        if (e->graphic < 0x8C || e->graphic > 0x8E) continue;
        {
            /* Collect: mark by zeroing graphic so it won't trigger again */
            e->graphic = 0x00;
            gs->keys_collected++;
            fprintf(stdout, "ACG key piece collected! (%d/3)\n", gs->keys_collected);
            if (gs->keys_collected >= 3)
                fprintf(stdout, "All 3 ACG keys! Find the exit (graphic 0x24)!\n");
        }
    }
    /* Check exit */
    if (gs->keys_collected >= 3) {
        for (int i = 0; i < gs->num_room_entities; i++) {
            const RoomEntity *e = &gs->room_entities[i];
            if (e->graphic != 0x24) continue;
            int dx = (int)gs->player.x - (int)e->x;
            int dy = (int)gs->player.y - (int)e->y;
            if (dx*dx + dy*dy < 144) {
                fprintf(stdout, "YOU WIN! Score: %u\n", gs->score_val);
                gs->running = 0;
            }
        }
    }
}

/*
 * has_key_for_door() — check if player carries a key matching the door's colour.
 * door_attr: ZX attr byte of the locked door entity.
 * Key colour = door attr bits 0-2 (ink). Key in inventory has graphic==0x81 and same ink bits.
 */
static int has_key_for_door(const GameState *gs, uint8_t door_attr) {
    uint8_t need_ink = door_attr & 0x07;
    for (int s = 0; s < 3; s++) {
        if (gs->inventory[s][2] == 0x81) {          /* graphic = key */
            if ((gs->inventory[s][3] & 0x07) == need_ink)
                return 1;
        }
    }
    return 0;
}

/*
 * do_room_transition() — move player to destination room via a linked door.
 * src_addr: ZX address of the door entity the player triggered.
 */
static void do_room_transition(GameState *gs, uint16_t src_addr) {
    const uint8_t *ram = gs->ram;
    if (!ram) return;

    /* Linked door is at src_addr XOR 0x08 */
    uint16_t dst_addr = (uint16_t)(src_addr ^ 0x08u);
    if (dst_addr < 0x4000u || dst_addr + 7u >= 0x10000u) return;
    uint16_t base = (uint16_t)(dst_addr - 0x4000u);
    uint8_t dst_room  = ram[base + 1];
    uint8_t dst_flags = ram[base + 2];
    uint8_t dst_x     = ram[base + 3];
    uint8_t dst_y     = ram[base + 4];

    /* New player position from linked door coords + flags offset */
    uint8_t new_x = (uint8_t)(dst_x + (dst_flags & 0x0Fu) * 2u);
    uint8_t new_y = (uint8_t)(dst_y - (uint8_t)(((dst_flags >> 3) & 0x1Eu)));

    gs->current_room  = dst_room;
    gs->room_style    = room_attrs[dst_room].style;
    gs->room_attr     = room_attrs[dst_room].attr;
    gs->player.x      = new_x;
    gs->player.y      = new_y;
    gs->num_creatures = 0;  /* Re-parse entities for the new room */
    parse_room_entities(gs, ram);
    fprintf(stdout, "door transition: room %02X -> %02X player=(%02X,%02X)\n",
            src_addr, dst_room, new_x, new_y);
}

/*
 * game_tick() — update game logic once per frame.
 * Energy drains over time; death/respawn handled here.
 */
static void game_tick(GameState *gs) {
    /* Advance clock: 1 second every 50 frames (FPS=50) */
    if (gs->frame % 50 == 0 && gs->frame > 0) {
        gs->clock_s++;
        if (gs->clock_s >= 60) {
            gs->clock_s = 0;
            gs->clock_m++;
        }
        if (gs->clock_m >= 60) {
            gs->clock_m = 0;
            gs->clock_h++;
        }
        if (gs->clock_h >= 24) {
            gs->clock_h = 0;
        }
    }

    /* Energy drain: -1 every 16 frames */
    if ((gs->frame & 0x0Fu) == 0u && gs->energy > 0)
        gs->energy--;

    /* Spawn a creature every 200 frames (max 3) */
    if (gs->frame % 200 == 0) spawn_creature(gs);

    /* Check item pickups */
    check_item_pickup(gs);

    /* Update weapon */
    update_weapon(gs);

    /* Update creature AI */
    update_creatures(gs);

    /* Death check */
    if (gs->energy == 0) {
        if (gs->lives > 0)
            gs->lives--;
        if (gs->lives == 0) {
            gs->running = 0;
            fprintf(stdout, "GAME OVER \u2014 score: %02X%02X%02X\n",
                gs->score[0], gs->score[1], gs->score[2]);
        } else {
            gs->energy     = 0xF0;
            gs->player.x   = 0x58;
            gs->player.y   = 0x68;
            gs->walk_dir   = 0;
            gs->walk_frame = 0;
            fprintf(stdout, "Respawn: lives=%d\n", gs->lives);
        }
    }
}

/*
 * render_room() — fill floor and draw walls for the current room.
 * Must be called each frame before rendering sprites.
 */
static void render_room(SDL_Renderer *ren, const GameState *gs) {
    const RoomStyle *rs = get_room_style(gs->current_room, NULL);

    /* Room centre and interior bounds */
    int cx = 0x58, cy = 0x68;
    int left   = (cx - rs->w) * SCALE;
    int right  = (cx + rs->w) * SCALE;
    int top    = (cy - rs->h) * SCALE;
    int bottom = (cy + rs->h) * SCALE;
    int thick  = 4 * SCALE;

    /* Decode ZX attribute → SDL colours */
    uint8_t attr  = gs->room_attr;
    int bright    = (attr & 0x40) ? 8 : 0;
    SDL_Color ink  = zx_pal[(attr & 7) | bright];
    SDL_Color paper= zx_pal[((attr >> 3) & 7) | bright];

    /* Fill floor with paper colour */
    SDL_SetRenderDrawColor(ren, paper.r, paper.g, paper.b, 255);
    SDL_Rect floor_r = { left, top, right - left, bottom - top };
    SDL_RenderFillRect(ren, &floor_r);

    /* Draw walls with ink colour */
    SDL_SetRenderDrawColor(ren, ink.r, ink.g, ink.b, 255);
    SDL_Rect walls[4] = {
        { left,        top - thick,   right - left,         thick              },  /* top    */
        { left,        bottom,        right - left,         thick              },  /* bottom */
        { left - thick, top - thick,  thick, bottom-top+2*thick               },  /* left   */
        { right,       top - thick,   thick, bottom-top+2*thick               },  /* right  */
    };
    for (int i = 0; i < 4; i++)
        SDL_RenderFillRect(ren, &walls[i]);

    /* Trapdoor indicator: style 12 gets dark hatching across the floor */
    if (room_attrs[gs->current_room].style == 12) {
        SDL_SetRenderDrawColor(ren, 40, 40, 40, 255);
        for (int tx = (cx - rs->w + 8) * SCALE; tx < (cx + rs->w - 8) * SCALE; tx += 16 * SCALE) {
            SDL_Rect trap = { tx, (cy - 4) * SCALE, 8 * SCALE, 8 * SCALE };
            SDL_RenderFillRect(ren, &trap);
        }
    }
}

int main(int argc, char *argv[]) {
    int headless = 0;
    for (int i = 1; i < argc; i++) {
        if (strcmp(argv[i], "--headless") == 0) headless = 1;
    }

    /* Allocate RAM */
    uint8_t *ram = calloc(RAM_SIZE, 1);
    if (!ram) { fprintf(stderr, "Out of memory\n"); return 1; }

    /* Game state */
    GameState gs;
    memset(&gs, 0, sizeof(gs));

    /* Load game data: full snapshot preferred, TAP fallback */
    if (!load_z80("atic_atac_full.z80", ram)) {
        if (!load_tap("ATIC_ATAC.TAP", ram)) {
            fprintf(stderr, "Using blank RAM (no valid snapshot)\n");
        }
    }

    /* Init game state from snapshot */
    init_game(&gs, ram);
    gs.ram = ram;
    parse_room_table(&gs, ram);
    parse_room_entities(&gs, ram);

    /* SDL init */
    if (SDL_Init(SDL_INIT_VIDEO) != 0) {
        fprintf(stderr, "SDL_Init: %s\n", SDL_GetError());
        free(ram);
        return 1;
    }

    Uint32 win_flags = headless ? SDL_WINDOW_HIDDEN : 0;
    SDL_Window *win = SDL_CreateWindow(
        "Atic Atac — ZX Spectrum Port",
        SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED,
        WIN_W, WIN_H, win_flags);
    if (!win) {
        fprintf(stderr, "SDL_CreateWindow: %s\n", SDL_GetError());
        SDL_Quit(); free(ram); return 1;
    }

    SDL_Renderer *ren = SDL_CreateRenderer(win, -1,
        SDL_RENDERER_ACCELERATED | SDL_RENDERER_PRESENTVSYNC);
    if (!ren) {
        SDL_DestroyWindow(win); SDL_Quit(); free(ram); return 1;
    }
    SDL_RenderSetLogicalSize(ren, WIN_W, WIN_H);

    /* Character select (skip in headless mode) */
    if (!headless) {
        gs.char_type = (uint8_t)show_char_select(ren);
    }

    SDL_Texture *tex = SDL_CreateTexture(ren,
        SDL_PIXELFORMAT_ARGB8888,
        SDL_TEXTUREACCESS_STREAMING,
        SCREEN_W, SCREEN_H);
    if (!tex) {
        SDL_DestroyRenderer(ren); SDL_DestroyWindow(win); SDL_Quit(); free(ram); return 1;
    }

    SDL_Rect dst = {0, 0, WIN_W, WIN_H};
    (void)dst;  /* kept for future sprite blit */

    /* Main loop */
    while (gs.running) {
        SDL_Event ev;
        while (SDL_PollEvent(&ev)) {
            if (ev.type == SDL_QUIT) gs.running = 0;
            if (ev.type == SDL_KEYDOWN && ev.key.keysym.sym == SDLK_ESCAPE) gs.running = 0;
            if (ev.type == SDL_KEYDOWN && ev.key.keysym.sym == SDLK_SPACE) fire_weapon(&gs);
        }

        /* Player movement — arrow keys / WASD, 2px per frame */
        {
            const Uint8 *keys = SDL_GetKeyboardState(NULL);
            int nx = gs.player.x;
            int ny = gs.player.y;
            int moved = 0;

            if (keys[SDL_SCANCODE_LEFT]  || keys[SDL_SCANCODE_A])
                { nx -= 2; gs.walk_dir = 2; moved = 1; }
            if (keys[SDL_SCANCODE_RIGHT] || keys[SDL_SCANCODE_D])
                { nx += 2; gs.walk_dir = 1; moved = 1; }
            if (keys[SDL_SCANCODE_UP]    || keys[SDL_SCANCODE_W])
                { ny -= 2; gs.walk_dir = 3; moved = 1; }
            if (keys[SDL_SCANCODE_DOWN]  || keys[SDL_SCANCODE_S])
                { ny += 2; gs.walk_dir = 0; moved = 1; }

            /* Door-based room transitions: check proximity to door entities */
            for (int di = 0; di < gs.num_room_entities; di++) {
                const RoomEntity *re = &gs.room_entities[di];
                int is_normal = (re->graphic >= 0x01 && re->graphic <= 0x03);
                int is_locked = (re->graphic >= 0x08 && re->graphic <= 0x0B);
                if (!is_normal && !is_locked) continue;
                int ddx = nx - (int)re->x;
                int ddy = ny - (int)re->y;
                if (ddx*ddx + ddy*ddy < 144) { /* 12px trigger radius */
                    if (is_locked && !has_key_for_door(&gs, re->attr)) {
                        /* No key — block player at door position */
                        nx = (int)re->x;
                        ny = (int)re->y;
                        break;
                    }
                    do_room_transition(&gs, re->zx_addr);
                    nx = gs.player.x;
                    ny = gs.player.y;
                    break;
                }
            }
            /* Clamp to room interior if no transition triggered */
            {
                const RoomStyle *rs2 = get_room_style(gs.current_room, NULL);
                int cx2 = 0x58, cy2 = 0x68;
                int lb = cx2 - rs2->w + 4;
                int rb = cx2 + rs2->w - 4 - 16;
                int tb = cy2 - rs2->h + 4;
                int bb = cy2 + rs2->h - 4 - 18;
                if (nx < lb) nx = lb;
                if (nx > rb) nx = rb;
                if (ny < tb) ny = tb;
                if (ny > bb) ny = bb;
            }

            gs.player.x = (uint8_t)nx;
            gs.player.y = (uint8_t)ny;

            /* Advance walk animation every 6 frames when moving */
            if (moved && (gs.frame % 6 == 0))
                gs.walk_frame = (gs.walk_frame + 1) & 3;
        }

        SDL_SetRenderDrawColor(ren, 0, 0, 0, 255);  /* ZX border: black */
        SDL_RenderClear(ren);
        render_room(ren, &gs);
        render_items(ren, &gs);
        render_decorations(ren, &gs);
        render_player(ren, &gs);
        render_creatures(ren, &gs);
        render_weapon(ren, &gs);
        render_hud(ren, &gs);
        SDL_RenderPresent(ren);

        if (headless) {
            fprintf(stdout, "Headless: frame rendered OK\n");
            gs.running = 0;
        } else {
            SDL_Delay(1000 / FPS);
        }

        gs.frame++;
        game_tick(&gs);
    }

    /* Game over overlay: red tint for 2 seconds */
    if (!headless && gs.energy == 0 && gs.lives == 0) {
        SDL_SetRenderDrawBlendMode(ren, SDL_BLENDMODE_BLEND);
        SDL_SetRenderDrawColor(ren, 200, 0, 0, 128);
        SDL_Rect overlay = {0, 0, WIN_W, WIN_H};
        SDL_RenderFillRect(ren, &overlay);
        SDL_RenderPresent(ren);
        SDL_Delay(2000);
    }

    SDL_DestroyTexture(tex);
    SDL_DestroyRenderer(ren);
    SDL_DestroyWindow(win);
    SDL_Quit();
    free(ram);
    return 0;
}

/*
 * render_decorations() — draw room decoration entities (graphic 0x10-0x7F).
 */
static void render_decorations(SDL_Renderer *ren, const GameState *gs) {
    for (int i = 0; i < gs->num_room_entities; i++) {
        const RoomEntity *e = &gs->room_entities[i];
        /* Render normal doors (0x01-0x03) with real sprites */
        if (e->graphic >= 0x01 && e->graphic <= 0x03) {
            static const uint8_t (*norm_doors[3])[2] = { door_normal_0, door_normal_1, door_normal_2 };
            draw_sprite(ren, norm_doors[e->graphic - 1], 18, e->x, e->y, e->attr, 1);
            continue;
        }
        /* Render locked doors (0x08-0x0B) with real sprites */
        if (e->graphic >= 0x08 && e->graphic <= 0x0B) {
            static const uint8_t (*lock_doors[4])[2] = { door_locked_0, door_locked_1, door_locked_2, door_locked_3 };
            draw_sprite(ren, lock_doors[e->graphic - 0x08], 18, e->x, e->y, e->attr, 1);
            continue;
        }
        if (e->graphic < 0x10 || e->graphic >= 0x80) continue;
        /* Known decorations: use real ROM sprites */
        switch (e->graphic) {
            case 0x10: draw_sprite(ren, deco_clock,      18, e->x, e->y, e->attr, 1); continue;
            case 0x17: draw_sprite(ren, deco_bookcase,   20, e->x, e->y, e->attr, 1); continue;
            case 0x18: draw_sprite(ren, trapdoor_closed, 20, e->x, e->y, e->attr, 1); continue;
            case 0x19: draw_sprite(ren, trapdoor_open,   20, e->x, e->y, e->attr, 1); continue;
            case 0x1A: draw_sprite(ren, deco_barrel,     20, e->x, e->y, e->attr, 1); continue;
            default: break;
        }
        /* Fallback: coloured square for unknown decoration IDs */
        {
            int bright2 = (e->attr & 0x40) ? 1 : 0;
            int ci2 = e->attr & 0x07;
            int idx2 = ci2 + (bright2 ? 8 : 0);
            SDL_Color c2 = zx_pal[idx2];
            SDL_SetRenderDrawColor(ren, c2.r, c2.g, c2.b, 255);
            SDL_Rect r2 = { e->x * SCALE, e->y * SCALE, 8 * SCALE, 8 * SCALE };
            SDL_RenderFillRect(ren, &r2);
        }
    }
}

/*
 * render_creatures() — draw all active creatures in current room.
 * Uses creature_sprites[type][frame] where type = graphic & 0x1F (clamped to 21)
 * and frame cycles at 8-frame intervals (4 frames total).
 */
static void render_creatures(SDL_Renderer *ren, const GameState *gs) {
    for (int i = 0; i < gs->num_creatures; i++) {
        const Entity *e = &gs->creatures[i];
        if (e->room != gs->current_room) continue;
        int type  = (e->graphic & 0x1F);
        if (type > 21) type = 0;
        int frame = (gs->frame / 8) & 3;
        draw_sprite(ren, creature_sprites[type][frame], CREATURE_ROWS, e->x, e->y, e->attr, 1);
    }
}


/*
 * show_char_select() - blocking character selection screen.
 * Returns 0=Knight, 1=Wizard, 2=Serf. ESC/Q defaults to Knight.
 */
static int show_char_select(SDL_Renderer *ren) {
    static const char *names[3] = {"KNIGHT", "WIZARD", "SERF"};
    static const uint8_t colours[3] = {0x47, 0x45, 0x43}; /* white, cyan, green */
    int selected = 0;
    int done = 0;

    while (!done) {
        /* Clear to black */
        SDL_SetRenderDrawColor(ren, 0, 0, 0, 255);
        SDL_RenderClear(ren);

        /* Draw title "ATIC ATAC" */
        draw_text(ren, "ATIC ATAC", 80, 20, 255, 255, 0);   /* yellow */

        /* Draw "SELECT CHARACTER" prompt */
        draw_text(ren, "SELECT CHARACTER", 55, 55, 200, 200, 200);

        /* Draw 3 character options */
        for (int i = 0; i < 3; i++) {
            uint8_t attr = colours[i];
            int bright = (attr & 0x40) ? 255 : 180;
            int ci     = attr & 0x07;
            int r = (ci & 2) ? bright : 0;
            int g = (ci & 4) ? bright : 0;
            int b = (ci & 1) ? bright : 0;

            int oy = 80 + i * 30;

            /* Selection indicator */
            if (i == selected) {
                SDL_SetRenderDrawColor(ren, 255, 255, 0, 255);
                SDL_Rect arrow = { 50 * SCALE, oy * SCALE, 6 * SCALE, 10 * SCALE };
                SDL_RenderFillRect(ren, &arrow);
            }

            /* Character colour block */
            SDL_SetRenderDrawColor(ren, r, g, b, 255);
            SDL_Rect box = { 60 * SCALE, oy * SCALE, 12 * SCALE, 12 * SCALE };
            SDL_RenderFillRect(ren, &box);

            /* Character name text */
            draw_text(ren, names[i], 80, oy + 2, 200, 200, 200);
        }

        SDL_RenderPresent(ren);

        SDL_Event ev;
        while (SDL_PollEvent(&ev)) {
            if (ev.type == SDL_QUIT) return 0;
            if (ev.type == SDL_KEYDOWN) {
                switch (ev.key.keysym.sym) {
                    case SDLK_UP:   selected = (selected + 2) % 3; break;
                    case SDLK_DOWN: selected = (selected + 1) % 3; break;
                    case SDLK_RETURN:
                    case SDLK_SPACE: done = 1; break;
                    case SDLK_ESCAPE:
                    case SDLK_q:    return 0;
                    default: break;
                }
            }
        }
        SDL_Delay(16);
    }
    return selected;
}

/*
 * fire_weapon() — launch axe from player position in walk_dir direction.
 */
static void fire_weapon(GameState *gs) {
    if (gs->weapon_active) return;  /* already in flight */
    gs->weapon_active = 1;
    gs->weapon_room   = gs->current_room;
    gs->weapon.x      = gs->player.x;
    gs->weapon.y      = gs->player.y;
    /* Colour and sprite vary by character */
    switch (gs->char_type) {
        case 1:  gs->weapon.attr = 0x44; break; /* Wizard: bright cyan  */
        case 2:  gs->weapon.attr = 0x42; break; /* Serf:   bright red   */
        default: gs->weapon.attr = 0x46; break; /* Knight: bright yellow */
    }
    /* Velocity: 4px/frame in walk direction */
    static const int8_t dvx[4] = { 0, 4, -4, 0 };  /* down,right,left,up */
    static const int8_t dvy[4] = { 4, 0,  0,-4 };
    gs->weapon.vx = dvx[gs->walk_dir];
    gs->weapon.vy = dvy[gs->walk_dir];
    gs->weapon_life = 48; /* 48-frame lifetime */
}

/*
 * update_weapon() — move axe, check creature collisions.
 */
static void update_weapon(GameState *gs) {
    if (!gs->weapon_active) return;
    if (gs->weapon_room != gs->current_room) { gs->weapon_active = 0; return; }

    gs->weapon.x = (uint8_t)((int)gs->weapon.x + gs->weapon.vx);
    gs->weapon.y = (uint8_t)((int)gs->weapon.y + gs->weapon.vy);

    /* Lifetime countdown */
    if (gs->weapon_life > 0) gs->weapon_life--;
    if (gs->weapon_life == 0) {
        gs->weapon_active = 0;
        return;
    }

    /* Bounce off room walls */
    {
        const RoomStyle *rs = get_room_style(gs->current_room, NULL);
        int cx = 0x80, cy = 0x60;
        int wl = cx - rs->w + 4, wr = cx + rs->w - 4;
        int wt = cy - rs->h + 4, wb = cy + rs->h - 4;
        if ((int)gs->weapon.x <= wl || (int)gs->weapon.x >= wr) gs->weapon.vx = -gs->weapon.vx;
        if ((int)gs->weapon.y <= wt || (int)gs->weapon.y >= wb) gs->weapon.vy = -gs->weapon.vy;
    }

    /* Hit detection vs creatures */
    for (int i = 0; i < gs->num_creatures; i++) {
        Entity *e = &gs->creatures[i];
        if (e->room != gs->current_room) continue;
        int dx = (int)gs->weapon.x - (int)e->x;
        int dy = (int)gs->weapon.y - (int)e->y;
        if (dx*dx + dy*dy < 144) {  /* 12px hit radius */
            /* Kill creature: save graphic before swapping */
            uint8_t killed_graphic = gs->creatures[i].graphic;
            gs->creatures[i] = gs->creatures[gs->num_creatures - 1];
            gs->num_creatures--;
            gs->weapon_active = 0;
            /* Per-creature score (type from graphic & 0x1F) */
            {
                static const uint32_t score_table[22] = {
                    100,100,100,100,  /* 0-3:  ghosts */
                    150,150,150,150,  /* 4-7:  demons */
                    200,200,200,200,  /* 8-11: mummies */
                    250,250,250,250,  /* 12-15: bosses */
                    300,300,300,300,300,300  /* 16-21: rare */
                };
                uint8_t ctype = killed_graphic & 0x1Fu;
                if (ctype > 21u) ctype = 0;
                gs->score_val += score_table[ctype];
            }
            /* Pack back into BCD score[3] */
            uint32_t s = gs->score_val;
            gs->score[2] = (uint8_t)(((s / 10) % 10) << 4 | (s % 10));
            gs->score[1] = (uint8_t)(((s / 1000) % 10) << 4 | ((s / 100) % 10));
            gs->score[0] = (uint8_t)(((s / 100000) % 10) << 4 | ((s / 10000) % 10));
            fprintf(stdout, "Kill! score=%u\n", gs->score_val);
            break;
        }
    }
}


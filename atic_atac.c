/*
 * draw_text() — render an uppercase ASCII string at ZX pixel (px, py).
 * Each character is 4px wide, 6px tall, spaced 5px apart.
 * Spaces are 3px wide. Non-alpha/non-space characters are skipped.
 */
static void draw_text(SDL_Renderer *ren, const char *s, int px, int py,
                      uint8_t r, uint8_t g, uint8_t b) {
    int cx = px;
    for (int i = 0; s[i]; i++) {
        char c = s[i];
        if (c >= 'a' && c <= 'z') c = (char)(c - 32);
        if (c == ' ') { cx += 3; continue; }
        if (c < 'A' || c > 'Z') { cx += 5; continue; }
        int idx = c - 'A';
        for (int row = 0; row < 6; row++) {
            for (int col = 0; col < 4; col++) {
                if ((letter_font[idx][row] >> (3 - col)) & 1) {
                    SDL_SetRenderDrawColor(ren, r, g, b, 255);
                    SDL_Rect rc = { (cx + col) * SCALE, (py + row) * SCALE, SCALE, SCALE };
                    SDL_RenderFillRect(ren, &rc);
                }
            }
        }
        cx += 5;
    }
}

/*
 * render_hud() — draw right-side scroll panel HUD.
 * Layout (ZX pixel coords, right panel x=150–255, y=0–191):
 *   x=150: left edge of HUD panel
 *   Scroll border, key icon, TIME, SCORE, inventory grid, lives, ACG keys
 */
static void render_hud(SDL_Renderer *ren, const GameState *gs) {
    /* ── HUD panel layout constants (ZX pixel coords) ── */
    const int HX  = 150;      /* HUD left edge */
    const int HW  = 106;      /* HUD width (to x=255) */
    const int HCX = HX + HW/2; /* HUD centre x = 203 */

    /* ── Panel background: black fill over room so HUD is readable ── */
    SDL_SetRenderDrawColor(ren, 0, 0, 0, 255);
    SDL_Rect panel = { HX * SCALE, 0, HW * SCALE, SCREEN_H * SCALE };
    SDL_RenderFillRect(ren, &panel);

    /* ── Scroll border: cyan double outline ── */
    SDL_SetRenderDrawColor(ren, 0, 215, 215, 255);
    SDL_Rect border1 = { HX*SCALE,       0,          HW*SCALE,       SCREEN_H*SCALE       };
    SDL_Rect border2 = { (HX+2)*SCALE,   2*SCALE,    (HW-4)*SCALE,   (SCREEN_H-4)*SCALE   };
    SDL_RenderDrawRect(ren, &border1);
    SDL_RenderDrawRect(ren, &border2);

    /* ── Key icon at top-centre (simple yellow cross shape, ZX y=6) ── */
    {
        int kx = HCX, ky = 7;
        SDL_SetRenderDrawColor(ren, 215, 215, 0, 255);
        /* Vertical bar of cross */
        SDL_Rect kv = { (kx-1)*SCALE, (ky-3)*SCALE, 2*SCALE, 6*SCALE };
        SDL_RenderFillRect(ren, &kv);
        /* Horizontal bar of cross */
        SDL_Rect kh = { (kx-3)*SCALE, (ky-1)*SCALE, 6*SCALE, 2*SCALE };
        SDL_RenderFillRect(ren, &kh);
        /* Key bow (circle-ish): top of key, 3px above cross */
        SDL_Rect kb = { (kx-2)*SCALE, (ky-6)*SCALE, 4*SCALE, 4*SCALE };
        SDL_RenderDrawRect(ren, &kb);
    }

    /* ── TIME label + clock (cyan, ZX y=18) ── */
    {
        /* Draw HH:MM:SS at HX+8, y=18 */
        int clk_digits[6] = {
            gs->clock_h / 10, gs->clock_h % 10,
            gs->clock_m / 10, gs->clock_m % 10,
            gs->clock_s / 10, gs->clock_s % 10,
        };
        int tx = HX + 8;
        for (int i = 0; i < 6; i++) {
            int cx2 = tx + i * 5 + (i >= 2 ? 2 : 0) + (i >= 4 ? 2 : 0);
            draw_digit(ren, clk_digits[i] % 10, cx2, 18, 0, 215, 215);
        }
    }

    /* ── SCORE label + 6 BCD digits (white/yellow flash, ZX y=30) ── */
    {
        int digits[6];
        digits[0] = (gs->score[0] >> 4) & 0xF;
        digits[1] =  gs->score[0]       & 0xF;
        digits[2] = (gs->score[1] >> 4) & 0xF;
        digits[3] =  gs->score[1]       & 0xF;
        digits[4] = (gs->score[2] >> 4) & 0xF;
        digits[5] =  gs->score[2]       & 0xF;
        uint8_t sr = 255, sg = 255;
        uint8_t sb = (gs->score_flash > 0 && (gs->score_flash / 4) & 1) ? 0u : 255u;
        int sx = HX + 8;
        for (int i = 0; i < 6; i++) {
            draw_digit(ren, digits[i] % 10, sx + i * 5, 30, sr, sg, sb);
        }
    }

    /* ── Inventory grid: up to 9 slots in 3 columns × 3 rows (ZX y=44–104) ── */
    /* Each slot is 12×12px with 2px gap. Top-left at HX+10, y=44 */
    {
        const int INV_X = HX + 10;
        const int INV_Y = 44;
        const int SLOT  = 12;
        const int GAP   = 2;
        /* Draw slot outlines */
        SDL_SetRenderDrawColor(ren, 80, 80, 80, 255);
        for (int row = 0; row < 3; row++) {
            for (int col = 0; col < 3; col++) {
                int sx2 = INV_X + col * (SLOT + GAP);
                int sy  = INV_Y + row * (SLOT + GAP);
                SDL_Rect slot = { sx2*SCALE, sy*SCALE, SLOT*SCALE, SLOT*SCALE };
                SDL_RenderDrawRect(ren, &slot);
            }
        }
        /* Draw inventory items — gs->inventory[i][2] = graphic ID (3 slots only) */
        for (int i = 0; i < 3; i++) {
            uint8_t gfx = gs->inventory[i][2];
            if (gfx == 0) continue; /* empty slot */
            int col = i % 3;
            int row = i / 3;
            int sx2  = INV_X + col * (SLOT + GAP) + 2;
            int sy   = INV_Y + row * (SLOT + GAP) + 2;
            /* Colour by item type */
            uint8_t ir = 215, ig = 215, ib = 0; /* default: yellow */
            if (gfx == 0x8A) { ir=215; ig=215; ib=215; } /* crucifix: white */
            if (gfx == 0x8B) { ir=100; ig=100; ib=100; } /* spanner: grey */
            if (gfx == 0x81) { ir=215; ig=0;   ib=0;   } /* key: red */
            SDL_SetRenderDrawColor(ren, ir, ig, ib, 255);
            SDL_Rect item = { sx2*SCALE, sy*SCALE, 8*SCALE, 8*SCALE };
            SDL_RenderFillRect(ren, &item);
        }
    }

    /* ── Lives: row of red squares at ZX y=114 ── */
    {
        int lx = HX + 10, ly = 114;
        SDL_SetRenderDrawColor(ren, 215, 0, 0, 255);
        for (int i = 0; i < gs->lives && i < 5; i++) {
            SDL_Rect heart = { (lx + i * 8)*SCALE, ly*SCALE, 6*SCALE, 6*SCALE };
            SDL_RenderFillRect(ren, &heart);
        }
    }

    /* ── ACG key pieces (yellow squares, ZX y=126) ── */
    {
        int kx = HX + 10, ky = 126;
        SDL_SetRenderDrawColor(ren, 215, 215, 0, 255);
        for (int i = 0; i < gs->keys_collected && i < 3; i++) {
            SDL_Rect kb = { (kx + i * 10)*SCALE, ky*SCALE, 8*SCALE, 8*SCALE };
            SDL_RenderFillRect(ren, &kb);
        }
    }

    /* ── Chicken energy bar (ZX-style proportional chicken silhouette) ── */
    /* Chicken is drawn top-down; clipped from bottom based on energy.
     * Full height = 60 ZX pixels (y=20 to y=80), positioned at HX+HW-22, y=20.
     * Each row of the chicken has an x-offset and width defining the silhouette.
     * 30 rows, each 2 ZX pixels tall → total 60px. */
    {
        /* Chicken silhouette: {x_offset, width} per row (0=top/head, 29=bottom/feet)
         * Rough side-view chicken: small head top-left, fat body middle, tail right, legs bottom */
        static const int8_t chk[30][2] = {
            { 4, 4},  /* 0: head top */
            { 3, 6},  /* 1: head */
            { 2, 8},  /* 2: head/beak */
            { 1,10},  /* 3: neck */
            { 0,12},  /* 4: neck-body */
            { 0,14},  /* 5: body top */
            { 0,16},  /* 6: body */
            { 0,16},  /* 7: body */
            { 0,16},  /* 8: body */
            { 0,18},  /* 9: body wide */
            { 0,18},  /* 10: body wide */
            { 0,18},  /* 11: body wide */
            { 0,16},  /* 12: body */
            { 0,16},  /* 13: body */
            { 1,15},  /* 14: belly */
            { 1,14},  /* 15: belly */
            { 2,12},  /* 16: lower body */
            { 2,10},  /* 17: lower body */
            { 3, 8},  /* 18: lower taper */
            { 3, 8},  /* 19: lower taper */
            { 4, 4},  /* 20: leg gap top */
            { 4, 4},  /* 21: leg gap */
            { 3, 2},  /* 22: left leg */
            { 3, 2},  /* 23: left leg */
            { 3, 2},  /* 24: left leg */
            {10, 2},  /* 25: right leg */
            {10, 2},  /* 26: right leg */
            {10, 2},  /* 27: right leg */
            { 2, 4},  /* 28: feet */
            { 2, 4},  /* 29: feet */
        };
        int ckx  = HX + HW - 22; /* left edge of chicken bounding box */
        int cky  = 18;            /* top of chicken */
        int full = 60;            /* full chicken height in ZX pixels */
        /* How many pixels of chicken to show = proportional to energy */
        int show_h = (int)((gs->energy * full) / 0xF0);
        if (show_h < 1 && gs->energy > 0) show_h = 1;
        /* clip_top: how many pixels to clip from top (hide when low energy) */
        int clip_top = full - show_h;
        SDL_SetRenderDrawColor(ren, 0, 215, 0, 255);
        for (int row = 0; row < 30; row++) {
            int ry = cky + row * 2; /* ZX y of this row */
            /* Skip rows above the clip line */
            if ((ry - cky + 2) <= clip_top) continue;
            int rx = ckx + chk[row][0];
            int rw = chk[row][1];
            if (rw <= 0) continue;
            SDL_Rect r = { rx*SCALE, ry*SCALE, rw*SCALE, 2*SCALE };
            SDL_RenderFillRect(ren, &r);
        }
    }

    /* ── Exploration % (bottom of panel, ZX y=178) ── */
    {
        int visited = 0;
        for (int i = 0; i < 19; i++)
            for (int b = 0; b < 8; b++)
                if (gs->visited_rooms[i] & (1u << b)) visited++;
        int pct = (visited * 100) / 148;
        draw_digit(ren, pct / 10, HX + 10, 178, 80, 160, 80);
        draw_digit(ren, pct % 10, HX + 16, 178, 80, 160, 80);
    }

    (void)HCX; /* suppress unused-variable warning if key icon is disabled */
}

/*
 * render_player() — draw the animated sprite at its current position.
 * Selects frame based on walk direction and animation cycle.
 */
static void render_player(SDL_Renderer *ren, const GameState *gs) {
    static const int walk_cycle[4] = {0, 1, 2, 1};
    int sprite_idx = gs->walk_dir * 4 + walk_cycle[gs->walk_frame & 3];
    /* Pick sprite sheet and colour by character type */
    const uint8_t (*sheet)[2];
    uint8_t attr;
    switch (gs->char_type) {
        case 1:  sheet = wizard_sprites[sprite_idx]; attr = 0x45; break; /* cyan  */
        case 2:  sheet = serf_sprites[sprite_idx];   attr = 0x43; break; /* green */
        default: sheet = knight_sprites[sprite_idx]; attr = 0x47; break; /* white */
    }
    if (gs->player.attr) attr = gs->player.attr;
    draw_sprite(ren, sheet, 18, gs->player.x, gs->player.y, attr, 1);
}

